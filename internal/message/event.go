// Package message defines the event message that tracker-api writes to
// Kafka and analytics-processor reads from it. Both services import this
// package, so the type is the contract between them.
package message

import (
	"time"
	"uuid"
)

// Event is one user action in the user-events topic, encoded as JSON.
// The message key is SessionID, so all events of one session go to the
// same partition.
//
// Compatibility: fields may be added, but existing fields must not be
// renamed, removed or change their type. Readers must ignore unknown
// fields.
type Event struct {
	// EventID is generated by the client. A retried send carries the same
	// id, so duplicates can be found by it.
	EventID   uuid.UUID `json:"event_id"`
	SessionID uuid.UUID `json:"session_id"`
	Type      string    `json:"type"`
	ElementID string    `json:"element_id"`
	// Value is optional: the selected value for a slider, select, checkbox
	// or radio, or the input length for a text field. Omitted when nil.
	Value *string `json:"value,omitempty"`
	// ClientTS is the client clock, kept for reference only.
	ClientTS time.Time `json:"client_ts"`
	// ServerTS is the receive time set by tracker-api, in UTC.
	// Aggregation windows are based on it.
	ServerTS time.Time `json:"server_ts"`
}
