// Package domain holds the event type of analytics-processor and the pure
// aggregation rules on it: windows, funnel steps and popular values.
// It does not import other packages of the project.
package domain

import (
	"time"
	"uuid"
)

// EventType is the kind of user action. The values match the whitelist
// of tracker-api; it drops events of other types.
type EventType string

// Event types sent by the frontend tracker.
const (
	EventTypePageView EventType = "page_view"
	EventTypeClick    EventType = "click"
	EventTypeInput    EventType = "input"
	EventTypeChange   EventType = "change"
	EventTypeFocus    EventType = "focus"
	EventTypeBlur     EventType = "blur"
	EventTypeSubmit   EventType = "submit"
)

// Event is a user action as the aggregation sees it. The consumer converts
// message.Event into it, so the rules here do not depend on the Kafka
// message format.
type Event struct {
	SessionID uuid.UUID

	// EventID is generated by the client; kept for finding duplicates.
	EventID uuid.UUID

	// Type is the kind of user action, see EventType.
	Type EventType

	// ElementID is the id of the page element, or "page" for page_view.
	ElementID string

	// Value is the selected value, or the input length for a text field;
	// empty when the event has none.
	Value string

	// Time is the receive time set by tracker-api (ServerTS of the message).
	// Windows are based on it; the client clock is not trusted.
	Time time.Time
}
